from __future__ import annotations

from io import BytesIO
from pathlib import Path
import os
import time

import cv2
import pandas as pd
from PIL import Image
import streamlit as st
import torch
from ultralytics import YOLO

ROOT = Path(__file__).resolve().parent
DEFAULT_WEIGHTS = ROOT / "runs" / "defect_detection" / "train" / "weights" / "best.pt"
DISPLAY_NAMES = {
    "1_chongkong": "Punching hole",
    "2_hanfeng": "Weld line",
    "3_yueyawan": "Crescent gap",
    "4_shuiban": "Water spot",
    "5_youban": "Oil spot",
    "6_siban": "Silk spot",
    "7_yiwu": "Inclusion",
    "8_yahen": "Rolled pit",
    "9_zhehen": "Crease",
    "10_yaozhe": "Waist folding",
}

st.set_page_config(
    page_title="Industrial Defect Inspection",
    page_icon="🔎",
    layout="wide",
)

st.markdown(
    """
    <style>
      .block-container {padding-top: 1.6rem; padding-bottom: 2.5rem;}
      div[data-testid="stMetric"] {
        background: rgba(128, 128, 128, 0.08);
        border: 1px solid rgba(128, 128, 128, 0.18);
        padding: 14px 16px;
        border-radius: 12px;
      }
      .small-note {font-size: 0.88rem; opacity: 0.8;}
    </style>
    """,
    unsafe_allow_html=True,
)

st.title("Industrial Defect Inspection")
st.caption("Upload industrial surface images, locate defects, and export an inspection report.")

with st.sidebar:
    st.header("Inspection settings")
    weights_text = st.text_input(
        "Model checkpoint (.pt)",
        value=os.getenv("DEFECT_MODEL_PATH", str(DEFAULT_WEIGHTS)),
        help="By default, this uses the best checkpoint generated by train.py.",
    )
    confidence = st.slider(
        "Confidence threshold",
        min_value=0.05,
        max_value=0.95,
        value=0.35,
        step=0.05,
        help="Raise this value to reduce low-confidence detections. Thresholds affect missed defects too.",
    )
    image_size = st.select_slider("Inference image size", options=[320, 416, 512, 640, 768], value=640)
    if torch.cuda.is_available():
        device_label = st.selectbox("Inference device", ["GPU (recommended)", "CPU"])
        inference_device = 0 if device_label.startswith("GPU") else "cpu"
        st.success(f"CUDA available: {torch.cuda.get_device_name(0)}")
    else:
        st.info("CUDA is unavailable; inference will use the CPU.")
        inference_device = "cpu"
    st.divider()
    st.markdown("**Workflow**")
    st.markdown("1. Choose image(s).\n2. Run inspection.\n3. Review detections.\n4. Download CSV results.")

weights_path = Path(weights_text.strip()).expanduser()
if not weights_path.is_absolute():
    weights_path = (ROOT / weights_path).resolve()


@st.cache_resource(show_spinner="Loading defect detection model...")
def load_model(path_string: str) -> YOLO:
    return YOLO(path_string)


model = None
if weights_path.is_file():
    try:
        model = load_model(str(weights_path))
    except Exception as exc:
        st.error(f"Could not load the checkpoint: {exc}")
else:
    st.warning("Trained model not found yet.")
    st.markdown(
        "Run the dataset conversion and training commands in the project terminal, "
        "then return here."
    )
    st.code("python convert_dataset.py\npython train.py\nstreamlit run app.py", language="powershell")
    st.caption(f"Expected checkpoint: {weights_path}")

uploaded_files = st.file_uploader(
    "Upload industrial surface images",
    type=["jpg", "jpeg", "png", "bmp"],
    accept_multiple_files=True,
    help="Use images similar to the surface-defect dataset used to train the model.",
)

run_inspection = st.button(
    "Run inspection",
    type="primary",
    disabled=(model is None or not uploaded_files),
)

if run_inspection:
    records: list[dict] = []
    image_outputs: list[dict] = []
    total_start = time.perf_counter()

    progress = st.progress(0, text="Preparing images...")
    for index, uploaded in enumerate(uploaded_files, start=1):
        try:
            original = Image.open(BytesIO(uploaded.getvalue())).convert("RGB")
        except Exception as exc:
            st.error(f"Could not read {uploaded.name}: {exc}")
            progress.progress(index / len(uploaded_files), text=f"Skipped {uploaded.name}")
            continue

        start = time.perf_counter()
        try:
            prediction = model.predict(
                source=original,
                conf=float(confidence),
                imgsz=int(image_size),
                device=inference_device,
                verbose=False,
            )[0]
        except Exception as exc:
            st.error(f"Inference failed for {uploaded.name}: {exc}")
            progress.progress(index / len(uploaded_files), text=f"Failed {uploaded.name}")
            continue
        elapsed_ms = (time.perf_counter() - start) * 1000.0

        plotted_bgr = prediction.plot()
        annotated_rgb = cv2.cvtColor(plotted_bgr, cv2.COLOR_BGR2RGB)
        boxes = prediction.boxes
        detection_count = 0 if boxes is None else len(boxes)
        status = "DEFECT DETECTED" if detection_count else "NO DEFECT DETECTED"

        if boxes is not None and detection_count:
            for box in boxes:
                class_id = int(box.cls[0].item())
                class_names = prediction.names
                class_code = class_names.get(class_id, str(class_id)) if isinstance(class_names, dict) else class_names[class_id]
                class_name = DISPLAY_NAMES.get(class_code, class_code)
                confidence_score = float(box.conf[0].item())
                x1, y1, x2, y2 = [round(float(value), 1) for value in box.xyxy[0].tolist()]
                records.append(
                    {
                        "Image": uploaded.name,
                        "Inspection status": status,
                        "Defect class": class_name,
                        "Confidence": round(confidence_score, 4),
                        "x1": x1,
                        "y1": y1,
                        "x2": x2,
                        "y2": y2,
                        "Inference time (ms)": round(elapsed_ms, 2),
                    }
                )
        else:
            records.append(
                {
                    "Image": uploaded.name,
                    "Inspection status": status,
                    "Defect class": "None detected at selected threshold",
                    "Confidence": None,
                    "x1": None,
                    "y1": None,
                    "x2": None,
                    "y2": None,
                    "Inference time (ms)": round(elapsed_ms, 2),
                }
            )

        image_outputs.append(
            {
                "name": uploaded.name,
                "original": original,
                "annotated": annotated_rgb,
                "status": status,
                "detections": detection_count,
                "elapsed_ms": elapsed_ms,
            }
        )
        progress.progress(index / len(uploaded_files), text=f"Inspected {index} of {len(uploaded_files)} images")

    progress.empty()
    total_seconds = time.perf_counter() - total_start

    if image_outputs:
        images_checked = len(image_outputs)
        images_with_detections = sum(item["detections"] > 0 for item in image_outputs)
        detection_total = sum(item["detections"] for item in image_outputs)
        mean_ms = sum(item["elapsed_ms"] for item in image_outputs) / images_checked

        st.subheader("Inspection summary")
        metric_cols = st.columns(4)
        metric_cols[0].metric("Images inspected", images_checked)
        metric_cols[1].metric("Images with detections", images_with_detections)
        metric_cols[2].metric("Defect boxes", detection_total)
        metric_cols[3].metric("Average inference", f"{mean_ms:.0f} ms")

        st.caption(
            f"Batch elapsed time: {total_seconds:.2f} seconds. "
            "A lack of detections does not prove a product is defect-free; results depend on the model, "
            "image quality, dataset coverage, and confidence threshold."
        )

        st.subheader("Image results")
        for output_index, item in enumerate(image_outputs):
            with st.expander(
                f"{item['name']} — {item['status']} ({item['detections']} detection(s))",
                expanded=True,
            ):
                left, right = st.columns(2)
                with left:
                    st.image(item["original"], caption="Original image", use_container_width=True)
                with right:
                    st.image(item["annotated"], caption="Detected defects", use_container_width=True)
                    image_buffer = BytesIO()
                    Image.fromarray(item["annotated"]).save(image_buffer, format="PNG")
                    st.download_button(
                        "Download annotated image",
                        data=image_buffer.getvalue(),
                        file_name=f"{Path(item['name']).stem}_annotated.png",
                        mime="image/png",
                        key=f"download_{output_index}_{item['name']}",
                    )

        st.subheader("Detection details")
        results_df = pd.DataFrame(records)
        st.dataframe(results_df, use_container_width=True, hide_index=True)
        csv_bytes = results_df.to_csv(index=False).encode("utf-8-sig")
        st.download_button(
            "Download inspection report (CSV)",
            data=csv_bytes,
            file_name="industrial_defect_inspection.csv",
            mime="text/csv",
        )
else:
    st.info("Choose one or more images above, then select Run inspection.")
