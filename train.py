from __future__ import annotations

import argparse
from pathlib import Path
import sys

import torch
from ultralytics import YOLO

ROOT = Path(__file__).resolve().parent


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Fine-tune a pretrained YOLO model on industrial defect annotations."
    )
    parser.add_argument(
        "--data",
        type=Path,
        default=ROOT / "dataset_yolo" / "data.yaml",
        help="Path to the dataset YAML generated by convert_dataset.py.",
    )
    parser.add_argument(
        "--model",
        default="yolo26n.pt",
        help="Pretrained Ultralytics checkpoint (downloaded automatically when needed).",
    )
    parser.add_argument("--epochs", type=int, default=40)
    parser.add_argument("--imgsz", type=int, default=640)
    parser.add_argument("--batch", type=int, default=8, help="Use 4 if you run out of GPU memory.")
    parser.add_argument("--workers", type=int, default=2)
    parser.add_argument("--patience", type=int, default=10)
    parser.add_argument("--name", default="train", help="Run name under runs/defect_detection.")
    parser.add_argument("--device", default="auto", help="auto, 0 for the first NVIDIA GPU, or cpu.")
    parser.add_argument("--exist-ok", action="store_true", help="Allow reuse of an existing run directory.")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    data_path = args.data.resolve()

    if not data_path.is_file():
        print(
            f"Dataset config not found: {data_path}\n"
            "Run python convert_dataset.py first and confirm dataset_yolo/data.yaml exists.",
            file=sys.stderr,
        )
        raise SystemExit(1)

    if args.epochs < 1 or args.imgsz < 32 or args.batch < 1:
        raise SystemExit("epochs, imgsz, and batch must be positive values.")

    if args.device.lower() == "auto":
        device = 0 if torch.cuda.is_available() else "cpu"
    elif args.device.lower() == "cpu":
        device = "cpu"
    else:
        device = args.device

    print(f"PyTorch: {torch.__version__}")
    print(f"CUDA available: {torch.cuda.is_available()}")
    if torch.cuda.is_available():
        print(f"GPU: {torch.cuda.get_device_name(0)}")
    else:
        print("WARNING: CUDA is unavailable; training will run on CPU.")
    print(f"Dataset: {data_path}")
    print(f"Model: {args.model}")
    print(f"Device: {device}")
    print(f"Epochs: {args.epochs} | Image size: {args.imgsz} | Batch: {args.batch}")

    model = YOLO(args.model)
    model.train(
        data=str(data_path),
        epochs=args.epochs,
        imgsz=args.imgsz,
        batch=args.batch,
        workers=args.workers,
        patience=args.patience,
        device=device,
        project=str(ROOT / "runs" / "defect_detection"),
        name=args.name,
        exist_ok=args.exist_ok,
        seed=42,
        plots=True,
        amp=True,
        cache=False,
    )

    best_weights = ROOT / "runs" / "defect_detection" / args.name / "weights" / "best.pt"
    if best_weights.exists():
        print("\nTraining completed.")
        print(f"Best checkpoint: {best_weights}")
        print("Next: python evaluate.py")
        print("Then: streamlit run app.py")
    else:
        print(
            "\nTraining returned, but the expected best.pt was not found. "
            "Check the Ultralytics log for the actual run directory."
        )


if __name__ == "__main__":
    # Required by Windows multiprocessing DataLoader.
    main()
